"""Build/check the documentation system map; no product execution or network."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
from collections import Counter
from pathlib import Path
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
MAP = ROOT / "docs/map"
GENERATED = {
    "docs/map/AGENTS.md",
    "docs/map/routing.md",
    "docs/map/objects/_index.md",
    "docs/map/_meta/file-inventory.json",
}
IGNORED = {
    ".git", "node_modules", "__pycache__", ".venv", ".pytest_cache",
    ".turbo", "dist", "build", "coverage", ".codex", ".agents",
    ".tmp", ".pnpm-store", ".pnpm-cache",
}


def frontmatter(file: Path) -> dict[str, str]:
    text = file.read_text(encoding="utf-8")
    match = re.match(r"\A---\n(.*?)\n---\n", text, re.S)
    if not match:
        raise ValueError(f"Missing frontmatter: {file.relative_to(ROOT)}")
    return dict(line.split(": ", 1) for line in match[1].splitlines())


def source_path(relative: str) -> Path:
    file = (ROOT / relative).resolve()
    if not file.is_relative_to(ROOT) or not file.is_file():
        raise ValueError(f"Source is missing/outside workspace: {relative}")
    return file


def read_cards(folder: str, kind: str) -> list[tuple[Path, dict[str, str]]]:
    cards = []
    for file in sorted((MAP / folder).glob("*.md")):
        if file.name in {"CONTEXT.md", "_index.md"}:
            continue
        data = frontmatter(file)
        if data.get("type") != kind:
            raise ValueError(f"Wrong card type: {file.name}")
        if data.get("universe") not in {"live", "ghost", "leftover"}:
            raise ValueError(f"Wrong universe: {file.name}")
        if data.get("status") not in {"stub", "verified", "stale"}:
            raise ValueError(f"Wrong status: {file.name}")
        sources = json.loads(data.get("sources", "[]"))
        if not isinstance(sources, list) or not sources:
            raise ValueError(f"No source citations: {file.name}")
        for source in sources:
            source_path(source)
        if data["status"] == "verified":
            if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", data.get("verified_on", "")):
                raise ValueError(f"Missing verification date: {file.name}")
            if data.get("snapshot") != "_meta/file-inventory.json":
                raise ValueError(f"Missing working snapshot: {file.name}")
        if kind == "object":
            if data.get("runtime") not in {"not-applicable", "proposed", "implemented"}:
                raise ValueError(f"Wrong runtime state: {file.name}")
            if data["universe"] == "live":
                source_path(data["entity"])
            if data["universe"] == "ghost" and data["runtime"] != "proposed":
                raise ValueError(f"Ghost marked implemented: {file.name}")
            sections = ["Summary", "Why this shape", "Shape", "Connected to", "If you change this", "Surfaces", "See"]
        else:
            sections = ["Input → Movement → Output", "Why this shape", "Steps", "If you change this", "Surfaces", "See"]
        body = file.read_text(encoding="utf-8")
        for section in sections:
            if f"## {section}\n" not in body:
                raise ValueError(f"Missing section {section}: {file.name}")
        cards.append((file, data))
    return cards


def role(file: Path) -> str:
    relative = file.relative_to(ROOT).as_posix()
    if file.name in {"AGENTS.md", "CLAUDE.md", "routing.md", "README.md", "_index.md"}:
        return "catalog"
    if file.name == "CONTEXT.md" or relative.startswith("docs/contracts/") or re.fullmatch(r"S\d\d-T.*\.md", file.name):
        return "contract"
    if relative.startswith("docs/progress/") or relative == "docs/feature-parity.md":
        return "product"
    return "factory"


def project_files() -> list[Path]:
    files = []
    for directory, folders, names in os.walk(ROOT, followlinks=False):
        folders[:] = sorted(name for name in folders if name not in IGNORED and not (Path(directory) / name).is_symlink())
        for name in names:
            file = Path(directory) / name
            if name not in IGNORED and not file.is_symlink() and file.relative_to(ROOT).as_posix() not in GENERATED:
                files.append(file)
    return sorted(files)


def build_outputs(objects: list[tuple[Path, dict[str, str]]]) -> dict[str, bytes]:
    catalog = (MAP / "CLAUDE.md").read_bytes()
    rows = [
        "# Object Index", "", "Generated by `python scripts/build_icm_map.py`; edit cards, then rebuild.", "",
        "| Object | Universe | Card status | Runtime | Owning file / proposed path |",
        "|---|---|---|---|---|",
    ]
    for file, data in objects:
        title = re.search(r"^# (.+)$", file.read_text(encoding="utf-8"), re.M).group(1)
        rows.append(f"| [{title}]({file.name}) | {data['universe']} | {data['status']} | {data['runtime']} | `{data['entity']}` |")
    try:
        baseline = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True, capture_output=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        baseline = "unavailable"
    files = [{
        "path": file.relative_to(ROOT).as_posix(),
        "role": role(file),
        "sha256": hashlib.sha256(file.read_bytes()).hexdigest(),
    } for file in project_files()]
    snapshot = {
        "schema_version": 1,
        "scope": "Repository working files; source hashes identify the snapshot, not a product release.",
        "git_baseline": baseline,
        "generated_outputs_excluded": sorted(GENERATED),
        "excluded_directory_names": sorted(IGNORED),
        "external_consumers": "unknown; no existing path moved by initial mapping",
        "files": files,
    }
    return {
        "docs/map/AGENTS.md": catalog,
        "docs/map/routing.md": catalog,
        "docs/map/objects/_index.md": ("\n".join(rows) + "\n").encode(),
        "docs/map/_meta/file-inventory.json": (json.dumps(snapshot, indent=2, ensure_ascii=False) + "\n").encode(),
    }


def check_links() -> None:
    areas = [ROOT / "docs", ROOT / "implementation", ROOT / "scripts"]
    files = [ROOT / "AGENTS.md", ROOT / "CONTEXT.md", ROOT / "README.md"]
    files += [file for area in areas for file in area.rglob("*.md")]
    for file in files:
        for target in re.findall(r"\[[^\]\n]*\]\(([^)\n]+)\)", file.read_text(encoding="utf-8")):
            target = target.strip().strip("<>")
            parsed = urlsplit(target)
            if parsed.scheme or parsed.netloc or not parsed.path:
                continue
            resolved = (file.parent / unquote(parsed.path)).resolve()
            if not resolved.is_relative_to(ROOT) or not resolved.exists():
                raise ValueError(f"Broken local link: {file.relative_to(ROOT)} -> {target}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Validate generated output freshness without writing")
    args = parser.parse_args()
    objects = read_cards("objects", "object")
    processes = read_cards("processes", "process")
    ids = {file.stem for file, _ in objects}
    for file, data in processes:
        for field in ["consumes", "produces"]:
            if not set(json.loads(data[field])).issubset(ids):
                raise ValueError(f"Unknown process object: {file.name} {field}")
    if len((ROOT / "AGENTS.md").read_text(encoding="utf-8").splitlines()) > 60:
        raise ValueError("Root AGENTS.md exceeds the 60-line routing target")
    outputs = build_outputs(objects)
    for relative, content in outputs.items():
        destination = ROOT / relative
        if args.check:
            if not destination.is_file() or destination.read_bytes() != content:
                raise ValueError(f"Generated output is stale: {relative}; run without --check")
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(content)
    check_links()
    counts = Counter(data["universe"] for _, data in objects)
    action = "CHECK PASS" if args.check else "BUILD PASS"
    print(f"ICM MAP {action}: {len(objects)} objects ({counts['live']} live, {counts['ghost']} ghost); {len(processes)} documented processes.")
    print("Catalog twins, source citations, metadata, local links and working-file hashes checked.")
    print("Product implementation/security/tests NOT_VERIFIED by this documentation tool.")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, KeyError, TypeError) as exc:
        raise SystemExit(f"ICM MAP FAIL: {exc}") from exc
